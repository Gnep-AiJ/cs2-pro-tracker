import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { EnvHttpProxyAgent, setGlobalDispatcher } from 'undici';
setGlobalDispatcher(new EnvHttpProxyAgent());
const directory = 'outputs/release-20261009-portal';
const read = async file => JSON.parse(await readFile(directory + '/' + file, 'utf8'));
const before = await read('before.json'), after = await read('after.json');
assert.notEqual(before.before.id, after.before.id);
assert.ok(after.before.id.startsWith('96182b24-'));
assert.deepEqual(after.configs.production.secretNames.sort(), ['FACEIT_API_KEY', 'PANDASCORE_API_TOKEN']);
assert.deepEqual(before.configs.production.r2, after.configs.production.r2);
assert.deepEqual(before.configs.production.ai, after.configs.production.ai);
const first = await read('production-checks.json'), recheck = await read('standings-recheck.json');
assert.equal(first.report.filter(item => item.failed).length, 1);
assert.equal(recheck.stale, false);
assert.equal((await read('_api_players_simple.json')).player.id, 'ac71ba3c-d3d4-45e7-8be2-26aa3986867d');
const html = await (await fetch('https://cs2pro.pages.dev/?lang=zh', { signal: AbortSignal.timeout(20000) })).text();
const assets = [...new Set([...html.matchAll(/(?:src|href)="(\/assets\/[^"?#]+)"/g)].map(m => m[1]))];
const results = await Promise.allSettled(assets.map(async asset => {
  const response = await fetch('https://cs2pro.pages.dev' + asset, { signal: AbortSignal.timeout(20000) });
  assert.equal(response.status, 200, asset);
  const remote = Buffer.from(await response.arrayBuffer());
  assert.deepEqual(remote, await readFile('.cf-pages-release-cs2pro-20261009-portal-final' + asset), asset);
  return { asset, sha256: createHash('sha256').update(remote).digest('hex') };
}));
assert.ok(results.every(result => result.status === 'fulfilled'), 'Published asset bytes must match');
const report = { checkedAt: new Date().toISOString(), url: 'https://cs2pro.pages.dev/?lang=zh', deployment: after.before, rollback: before.before, publicAssets: results.map(result => result.value), checks: first.report.filter(item => !item.failed).concat(recheck), recoveredChecks: ['Valve standings returned a saved snapshot on first request; two subsequent reads returned official data. The original failed check is preserved.'], browser: { verified: ['Homepage shows new navigation and current FACEIT match data', 'Contact dialog opens and shows original WeChat image'], limitation: 'Repeated browser-tool timeouts prevented completing subsequent donation-tab and layout follow-up checks.' } };
await writeFile(directory + '/acceptance.json', JSON.stringify(report, null, 2));
console.log(JSON.stringify({ deployment: report.deployment, rollback: report.rollback, assetBytesVerified: assets.length, apiAndPageChecks: report.checks.length, browserLimitation: report.browser.limitation }, null, 2));
